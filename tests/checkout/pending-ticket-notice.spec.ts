import { execFileSync } from "node:child_process"
import { randomUUID } from "node:crypto"

import { expect, Page, test } from "@playwright/test"

import { CheckoutPage } from "./checkout-page"
import { acceptCookiesUpfront, MP_HOLDER, MP_TEST_CARDS } from "../helpers"

/**
 * Pending-ticket notice (S8b, cuarzosmx `odd/tasks/checkout-stock-hold-hardening.md`).
 *
 * A cart with an unpaid Mercado Pago ticket (OXXO, `mp_status` "pending") can still
 * be paid another way; the review step must warn the shopper not to pay the ticket
 * too. These tests stop at the review step: nothing is charged.
 *
 * An OXXO ticket cannot be generated by automation (Checkout Pro sandbox login is
 * blocked, see checkout.spec.ts), so the pending payment is seeded straight into
 * the LOCAL dev database, the same row the webhook writes for a pending ticket.
 * Database access: `docker exec <E2E_DB_CONTAINER> psql -U <E2E_DB_USER> -d <E2E_DB_NAME>`.
 */
const PRODUCT_HANDLE = process.env.E2E_PRODUCT_HANDLE ?? "catedrales-de-cuarzo-121"
const DB_CONTAINER = process.env.E2E_DB_CONTAINER ?? "cuarzosmx-postgres"
const DB_USER = process.env.E2E_DB_USER ?? "cuarzosmx"
const DB_NAME = process.env.E2E_DB_NAME ?? "cuarzosmx-db"

const NOTICE =
  "Tienes una ficha de pago pendiente para este carrito (por ejemplo, OXXO). Si pagas ahora con otro método, ya no pagues la ficha: si se pagan las dos, tendremos que reembolsarte una."

function sql(statement: string): string {
  return execFileSync(
    "docker",
    ["exec", DB_CONTAINER, "psql", "-U", DB_USER, "-d", DB_NAME, "-tAc", statement],
    { encoding: "utf8" }
  ).trim()
}

/** Only [A-Za-z0-9_] reaches the SQL text: ids are generated or read from our own cookie. */
function safe(value: string): string {
  if (!/^[A-Za-z0-9_]+$/.test(value)) {
    throw new Error(`Unexpected id: ${value}`)
  }
  return value
}

async function cartIdOf(page: Page): Promise<string> {
  const cookie = (await page.context().cookies()).find((c) => c.name === "_medusa_cart_id")
  expect(cookie?.value, "the storefront must have created a cart").toBeTruthy()
  return safe(cookie!.value)
}

/** Takes the checkout to the review step with an approved test card (tokenized, not charged). */
async function reachReview(checkout: CheckoutPage, beforePayment?: () => Promise<void>) {
  await checkout.addProductToCart(PRODUCT_HANDLE)
  await checkout.openCart()
  await checkout.proceedToCheckout()
  await checkout.fillShippingAddress()
  await checkout.selectShippingMethod()
  if (beforePayment) {
    await beforePayment()
  }
  await checkout.selectMercadoPagoCard()
  await checkout.fillCardForm({ ...MP_TEST_CARDS.creditMastercard, holder: MP_HOLDER.approved })
  await checkout.selectInstallments(1)
  await checkout.submitCardForm()
  await expect(checkout.testId("submit-order-button")).toBeVisible()
}

test.beforeEach(async ({ context }) => {
  await acceptCookiesUpfront(context)
})

test.describe("Checkout - pending ticket notice", () => {
  test(
    "warns before paying another way when the cart has an unpaid ticket",
    { tag: ["@e2e", "@checkout", "@mercadopago", "@CHECKOUT-E2E-PENDING-TICKET"] },
    async ({ page }) => {
      const checkout = new CheckoutPage(page)
      const rowId = `mpp_e2e_${randomUUID().replace(/-/g, "")}`
      let seeded = false

      try {
        await reachReview(checkout, async () => {
          const cartId = await cartIdOf(page)
          sql(
            `insert into mercadopago_payment (id, cart_id, payment_id, mp_status, source, amount, currency_code) ` +
              `values ('${rowId}', '${cartId}', 'e2e_${Date.now()}', 'pending', 'webhook', 1, 'mxn')`
          )
          seeded = true
        })

        const notice = checkout.testId("pending-ticket-notice")
        await expect(notice).toBeVisible()
        await expect(notice).toHaveText(NOTICE)
        // A notice, not a block: the shopper can still pay.
        await expect(checkout.testId("submit-order-button")).toBeEnabled()
      } finally {
        if (seeded) {
          sql(`delete from mercadopago_payment where id = '${safe(rowId)}'`)
        }
      }
    }
  )

  test(
    "shows no notice for a cart without a pending ticket",
    { tag: ["@e2e", "@checkout", "@mercadopago", "@CHECKOUT-E2E-PENDING-TICKET"] },
    async ({ page }) => {
      const checkout = new CheckoutPage(page)

      await reachReview(checkout)

      await expect(checkout.testId("submit-order-button")).toBeEnabled()
      await expect(checkout.testId("pending-ticket-notice")).toHaveCount(0)
    }
  )
})
